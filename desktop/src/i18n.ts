type MessageKey = keyof typeof messages.en;
type Variables = Record<string, string | number>;

function initialLocale(): Locale {
  try {
    return localStorage.getItem(STORAGE_KEY) === "fr" ? "fr" : "en";
  } catch {
    return "en";
  }
}

export const locale = ref<Locale>(initialLocale());

export function setLocale(value: Locale) {
  locale.value = value;
  document.documentElement.lang = value;
  try {
    localStorage.setItem(STORAGE_KEY, value);
  } catch {
    // A blocked localStorage must not prevent the desktop application from working.
  }
}

export function t(key: MessageKey, variables: Variables = {}): string {
  let value: string = messages[locale.value][key] ?? messages.en[key];
  for (const [name, replacement] of Object.entries(variables)) {
    value = value.split(`{${name}}`).join(String(replacement));
  }
  return value;
}

export function formatDate(timestamp: number): string {
  return new Intl.DateTimeFormat(locale.value === "fr" ? "fr-FR" : "en-US", {
    dateStyle: "medium",
    timeStyle: "short",
  }).format(new Date(timestamp));
}

export function stateLabel(state: string): string {
  const labels: Record<Locale, Record<string, string>> = {
    en: {
      running: "running",
      stopping: "stopping",
      completed: "completed",
      failed: "failed",
      recovery_required: "recovery required",
      planned: "planned",
      moved: "moved",
      skipped: "skipped",
      skipped_collision: "collision skipped",
    },
    fr: {
      running: "active",
      stopping: "arrêt en cours",
      completed: "terminée",
      failed: "échouée",
      recovery_required: "récupération requise",
      planned: "planifié",
      moved: "déplacé",
      skipped: "ignoré",
      skipped_collision: "collision ignorée",
    },
  };
  return labels[locale.value][state.toLowerCase()] ?? state;
}

